"""Generates banner.svg (README) and social-preview.svg (GitHub, 1280x640) from icon.svg.
Text uses the Inter font (SIL OFL); render to PNG on a machine that has it installed."""
import re, random
from pathlib import Path

here = Path(__file__).parent
icon = (here / "icon.svg").read_text()
inner = re.search(r"<svg[^>]*>(.*)</svg>", icon, re.S).group(1)
inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)

def icon_at(x, y, size, prefix):
    body = re.sub(r'id="(\w+)"', rf'id="{prefix}\1"', inner)
    body = re.sub(r"url\(#(\w+)\)", rf"url(#{prefix}\1)", body)
    return f'<svg x="{x}" y="{y}" width="{size}" height="{size}" viewBox="0 0 512 512">{body}</svg>'

def sheet(x0, y0, cols, rows, tile_w, tile_h, gap, seed, fade_dir):
    """Decorative contact sheet: tiles in muted blues, one orange accent."""
    rnd = random.Random(seed)
    shades = ["#7DD3FC", "#60A5FA", "#38BDF8", "#93C5FD", "#3B9EEA"]
    out = []
    for r in range(rows):
        for c in range(cols):
            t = c / max(cols - 1, 1) if fade_dir == "x" else r / max(rows - 1, 1)
            op = 0.10 + 0.55 * t
            col = rnd.choice(shades)
            out.append(f'<rect x="{x0 + c*(tile_w+gap)}" y="{y0 + r*(tile_h+gap)}" width="{tile_w}" height="{tile_h}" rx="8" fill="{col}" fill-opacity="{op:.2f}"/>')
    return "\n    ".join(out)

FONT = "Inter, 'Segoe UI', 'Helvetica Neue', Arial, sans-serif"
BG = """<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#232833"/><stop offset="1" stop-color="#12151B"/>
    </linearGradient>"""

def strip(w, y, h):
    """Film-strip edge with sprocket holes."""
    holes = "".join(f'<rect x="{x}" y="{y + (h-14)/2}" width="22" height="14" rx="4" fill="#0C0E12"/>' for x in range(18, w, 44))
    return f'<rect x="0" y="{y}" width="{w}" height="{h}" fill="#2A303C"/>{holes}'

banner = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="320" viewBox="0 0 1280 320">
  <!-- Video-Thumbnailer README banner. Generated by make_banners.py. -->
  <defs>{BG}</defs>
  <rect width="1280" height="320" fill="url(#bg)"/>
  {strip(1280, 0, 30)}
  {strip(1280, 290, 30)}
  <g>
    {sheet(944, 52, 3, 3, 96, 54, 12, 7, "x")}
  </g>
  <rect x="1160" y="118" width="96" height="54" rx="8" fill="#F7892E" fill-opacity="0.85"/>
  <path d="M1200 133 L1220 145 L1200 157 Z" fill="#FFFFFF"/>
  {icon_at(64, 64, 192, "i_")}
  <text x="290" y="158" font-family="{FONT}" font-size="64" font-weight="700" fill="#FFFFFF">Video-Thumbnailer</text>
  <text x="292" y="206" font-family="{FONT}" font-size="26" font-weight="500" fill="#A9B4C6">Contact sheets from your videos</text>
  <text x="292" y="244" font-family="{FONT}" font-size="20" font-weight="500" fill="#6E7A8E">Windows · Linux · macOS  —  GUI &amp; CLI  —  AGPL-3.0</text>
</svg>
"""

social = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">
  <!-- Video-Thumbnailer GitHub social preview (1280x640). Generated by make_banners.py. -->
  <defs>{BG}</defs>
  <rect width="1280" height="640" fill="url(#bg)"/>
  {strip(1280, 0, 40)}
  {strip(1280, 600, 40)}
  {icon_at(110, 150, 300, "s_")}
  <text x="470" y="292" font-family="{FONT}" font-size="76" font-weight="700" fill="#FFFFFF">Video-Thumbnailer</text>
  <text x="474" y="354" font-family="{FONT}" font-size="32" font-weight="500" fill="#A9B4C6">Contact sheets from your videos</text>
  <text x="474" y="404" font-family="{FONT}" font-size="24" font-weight="500" fill="#6E7A8E">Windows · Linux · macOS  —  GUI &amp; CLI  —  free &amp; open source</text>
  <g>
    {sheet(474, 456, 7, 1, 96, 54, 12, 3, "x")}
  </g>
</svg>
"""
(here / "banner.svg").write_text(banner)
